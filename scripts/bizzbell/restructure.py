"""bb restructure <stage>: rewrite a layer that failed its gate, with the restructure (Opus-class) model.

Sends the layer's target files, its references, and the failed questions with the judge's evidence; the model
returns {"files": {path: full new content}, "changes": [...]}. Each old file is kept as <file>.r<round>.
At most bizzbell.json gate.max_rounds (3) rounds per stage, tracked in project.json; after that it refuses
(RoundsExhausted) and the agent must ask the user (accept, edit by hand, or allow one more round with --extra).

Targets: rubric "restructure": {"targets": [...]}, else the layer's text files. Media layers name their prompt
file(s) as targets (the corrected prompts are then regenerated by the stage, within the budget)."""
import json
import os
import shutil

from . import gate, hidrogen, ledger as ledger_mod, project, util
from .errors import BBError, RoundsExhausted, UsageError

SYSTEM = (
    "You restructure one layer of a short-video project so that it passes its quality gate. You get the layer's "
    "file(s), the references it must follow, and the gate questions it failed with the judge's evidence. Fix "
    "every failed question without breaking the ones that passed; keep everything that already works, the "
    "language, and the format of each file. Never invent facts, claims or numbers that are not in the "
    "references. Return JSON only: {\"files\": {\"<path>\": \"<the complete new file content>\"}, "
    "\"changes\": [\"one line per change, naming the question id it fixes\"]}. Return every target file in full.")


def targets(ctx):
    """Relative paths the restructure may rewrite."""
    t = (ctx.rubric.get("restructure") or {}).get("targets")
    if t:
        return list(t)
    return [ctx.rel(p) for p in ctx.layer_files if gate._is_textfile(p)]


def rounds(root, stage_id):
    """(used, allowed) restructure rounds for a stage."""
    st = project.stage_state(root, stage_id)
    mx = int(project.load_settings(root).get("gate", {}).get("max_rounds", 3))
    return int(st.get("restructure_rounds", 0)), mx + int(st.get("extra_rounds", 0))


def allow_extra_round(root, stage_id, note=""):
    """Permission point 4: the user said yes to one more round. Logged in project.json."""
    def f(st):
        s = st.setdefault("stages", {}).setdefault(stage_id, {})
        s["extra_rounds"] = int(s.get("extra_rounds", 0)) + 1
        s.setdefault("log", []).append({"time": util.now(), "extra_round": s["extra_rounds"], "note": note})
    project.update_state(root, f)


def build_prompt(ctx, record, files):
    failed = gate.failed_questions(record)
    passed = [q for q in record["questions"] if q["value"] >= 1.0]
    parts = ["Stage: %s (%s). Gate run #%d scored %.1f; it needs %g%s."
             % (ctx.stage, ctx.rubric.get("title", ctx.stage), record["run"], record["score"], record["pass_score"],
                (" and these hard questions must not be no: " + ", ".join(record["hard_failed"]))
                if record["hard_failed"] else "")]
    for name, text in ctx.references.items():
        parts.append('<reference name="%s">\n%s\n</reference>' % (name, text[:gate.MAX_TEXT_CHARS]))
    fq = [{"id": q["id"], "question": q["text"], "hard": q["hard"], "answers": q["answers"],
           "evidence": q["evidence"]} for q in failed]
    parts.append("<failed_questions>\n%s\n</failed_questions>" % json.dumps(fq, ensure_ascii=False, indent=1))
    parts.append("<passed_questions>\n%s\n</passed_questions>"
                 % "\n".join("%s: %s" % (q["id"], q["text"]) for q in passed))
    for rel, text in files.items():
        parts.append('<file name="%s">\n%s\n</file>' % (rel, text))
    parts.append("<targets>\n%s\n</targets>" % "\n".join(files))
    parts.append('Return JSON only: {"files": {...every target in full...}, "changes": [...]}')
    return "\n\n".join(parts)


def _validate(obj, wanted):
    if not isinstance(obj, dict) or not isinstance(obj.get("files"), dict):
        raise ValueError('the reply must be {"files": {...}, "changes": [...]}')
    out = {}
    for rel, content in obj["files"].items():
        if rel not in wanted:
            raise ValueError("%s is not a target file" % rel)
        if not isinstance(content, str) or not content.strip():
            raise ValueError("%s came back empty" % rel)
        if rel.endswith(".json"):
            json.loads(content)
        out[rel] = content
    if not out:
        raise ValueError("no target file came back")
    return out, [str(c) for c in obj.get("changes", [])][:50]


def run(root, stage_id, extra=False, note=""):
    """One restructure round. Returns {stage, round, allowed, files, kept, changes, model, cost_inr}."""
    project.stage(stage_id)
    record = gate.latest(root, stage_id)
    if record is None:
        raise UsageError("no gate run for %s yet: run python3 scripts/bb.py gate %s first" % (stage_id, stage_id))
    if record["passed"]:
        raise UsageError("%s already passed its gate (#%d, %.1f); nothing to restructure"
                         % (stage_id, record["run"], record["score"]))
    if extra:
        allow_extra_round(root, stage_id, note)
    used, allowed = rounds(root, stage_id)
    if used >= allowed:
        raise RoundsExhausted(
            "%s has used all %d restructure rounds and still scores %.1f (needs %g). Stop and ask the user: accept "
            "it as it is, edit it by hand, or allow one more round (python3 scripts/bb.py restructure %s --extra)."
            % (stage_id, allowed, record["score"], record["pass_score"], stage_id))
    rubric = gate.load_rubric(root, stage_id)
    ctx = gate.GateContext(root, stage_id, rubric)
    if gate.layer_hash(ctx) != record.get("layer_hash"):
        raise UsageError("the %s layer changed after gate #%d: run python3 scripts/bb.py gate %s again first"
                         % (stage_id, record["run"], stage_id))
    wanted = targets(ctx)
    files = {}
    for rel in wanted:
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            raise UsageError("restructure target %s does not exist" % rel)
        files[rel] = util.read_text(p)
    model = project.model_for(root, "restructure")
    prompt = build_prompt(ctx, record, files)
    led = ledger_mod.Ledger(root)
    spent0 = led.summary()["spent_inr"]
    err = ""
    new = changes = None
    for _attempt in range(2):
        msg = prompt if not err else prompt + "\n\nYour previous reply was rejected: %s. Reply again." % err
        reply = led.call("chat", lambda: hidrogen.chat(msg, model, system_prompt=SYSTEM, temperature=0.3,
                                                       max_tokens=16000, json_mode=True),
                         model=model, purpose="restructure %s round %d" % (stage_id, used + 1))
        try:
            new, changes = _validate(hidrogen.parse_json_text(reply["text"]), wanted)
            break
        except ValueError as e:
            err = str(e)
    if new is None:
        raise BBError("the restructure model did not return usable files (%s). Nothing was changed; run it "
                      "again or edit by hand." % err)
    rnd = used + 1
    kept = []
    for rel, content in new.items():
        p = os.path.join(root, rel)
        shutil.copy2(p, "%s.r%d" % (p, rnd))
        kept.append("%s.r%d" % (rel, rnd))
        util.write_text(p, content)
    result = {"stage": stage_id, "round": rnd, "allowed": allowed, "gate": record["run"], "files": sorted(new),
              "kept": kept, "changes": changes, "model": model, "time": util.now(),
              "cost_inr": round(led.summary()["spent_inr"] - spent0, 2)}
    util.write_json(os.path.join(root, "gates", "%s.r%d.json" % (stage_id, rnd)), result)

    def f(st):
        s = st.setdefault("stages", {}).setdefault(stage_id, {})
        s["restructure_rounds"] = rnd
        s["status"] = "restructured"
        s.setdefault("history", []).append({"restructure": rnd, "after_gate": record["run"], "time": result["time"]})
    project.update_state(root, f)
    project.refresh(root)
    return result


def format_result(res):
    lines = ["restructured %s (round %d of %d, model %s, INR %.2f)"
             % (res["stage"], res["round"], res["allowed"], res["model"], res["cost_inr"])]
    for rel, old in zip(res["files"], sorted(res["kept"])):
        lines.append("  %s  (old kept as %s)" % (rel, old))
    for c in res["changes"][:10]:
        lines.append("  - %s" % c[:160])
    lines.append("next: python3 scripts/bb.py gate %s" % res["stage"])
    return "\n".join(lines)
